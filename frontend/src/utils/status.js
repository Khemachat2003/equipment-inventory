// status.js — กติกา "สถานะ" ที่ใช้ร่วมกันทั้งระบบ (หน้าแรก · ทะเบียนรายชิ้น)
//
// ค่าข้อมูลจริงในชีต (Asset_List คอลัมน์ F): ใช้งานได้ / สำรอง / ส่งซ่อม / ชำรุด/สูญหาย / In Bundle
// ค่าอื่นที่อาจพบจากข้อมูลเดิม/ฟอร์มโอนย้าย: รอซ่อม · Damaged (ค่าอังกฤษ legacy)
// ใช้ function กลางที่นี่เสมอ เพื่อให้ "ตัวเลขบนการ์ดหน้าแรก" ตรงกับ "รายการที่กรองเจอที่ /asset" เป๊ะ

/**
 * สถานะ "ต้องซ่อม/ชำรุด" — ใช้กับการ์ด "ส่งซ่อม" หน้าแรก + ตัวกรอง deep-link ?status=repair
 * นับเมื่อค่าสถานะมีคำ: ซ่อม (ส่งซ่อม/รอซ่อม) · ชำรุด · สูญ (สูญหาย) · Damaged
 * @param {string} status ค่าสถานะดิบจากข้อมูล
 * @returns {boolean} true = อยู่ในกลุ่มต้องซ่อม/ชำรุด
 */
export function isRepairStatus(status) {
  const s = String(status || '');
  return s.includes('ซ่อม') || s.includes('ชำรุด') || s.includes('สูญ') || s.includes('Damaged');
}

/**
 * สถานะ "ใช้งานได้ / ปกติ" — ตรงข้ามกับกลุ่มต้องซ่อม/ชำรุด (กฎเดียวกันทุกหน้า)
 * ครอบคลุมทุกสถานะปกติ: ใช้งานได้ · สำรอง · In Bundle (สมาชิกชุดที่ถูกบังคับสถานะเป็น "In Bundle"
 * เมื่อจัดเข้าชุด — ดู routes/bundle.js) · ค่าว่าง (ติดตั้งแล้วแต่ไม่ได้ระบุสถานะ)
 * ใช้กับการ์ดฟาร์ม/ชุดติดตั้ง "ใช้งานได้ N" — ห้ามกรองเฉพาะคำ "ใช้งานได้" ที่ทำให้สมาชิกชุดโดนนับเป็น 0
 * @param {string} status ค่าสถานะดิบจากข้อมูล
 * @returns {boolean} true = อยู่ในกลุ่มใช้งานได้/ปกติ
 */
export function isUsableStatus(status) {
  return !isRepairStatus(status);
}
